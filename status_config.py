# 4. 헬퍼 함수
# ==============================================================================

def get_status_icon(status: str) -> str:
    """상태 아이콘 반환"""
    return STATUS_CONFIG.get(status, {}).get("icon", "❓")

def get_status_color(status: str) -> str:
    """상태 색상 반환"""
    return STATUS_CONFIG.get(status, {}).get("color", "#6B7280")

def get_status_bg(status: str) -> str:
    """상태 배경 색상 반환"""
    return STATUS_CONFIG.get(status, {}).get("bg", "#F3F4F6")

def get_status_badge_html(status: str) -> str:
    """상태 배지 HTML 반환"""
    cfg = STATUS_CONFIG.get(status, {"icon": "❓", "color": "#6B7280", "bg": "#F3F4F6"})
    return f'<span style="background:{cfg["bg"]};color:{cfg["color"]};padding:4px 12px;border-radius:12px;font-weight:700;font-size:13px;">{cfg["icon"]} {status}</span>'

def get_next_statuses(current_status: str) -> list:
    """현재 상태에서 전환 가능한 다음 상태 목록"""
    return STATUS_TRANSITIONS.get(current_status, [])

def get_status_progress(status: str) -> int:
    """상태의 진행률 (0~100%) 반환"""
    if status in STATUS_EXIT:
        return 0
    try:
        idx = STATUS_FLOW.index(status)
        return int((idx + 1) / len(STATUS_FLOW) * 100)
    except ValueError:
        return 0

def get_status_step(status: str) -> int:
    """상태의 단계 번호 (1~7) 반환. 이탈 상태는 0"""
    if status in STATUS_EXIT:
        return 0
    try:
        return STATUS_FLOW.index(status) + 1
    except ValueError:
        return 0

