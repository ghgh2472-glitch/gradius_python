def show_status():
    """현재 샘플 데이터 현황"""
    client = db.get_connection()
    if not client:
        print("❌ Google Sheets 연결 실패")
        return

    sh = client.open_by_key(db.SHEET_ID)
    print("=" * 60)
    print("📊 샘플 데이터 현황 (접두사: 'SAMPLE-')")
    print("=" * 60)

    for sheet_name, id_col in SHEET_INQ_ID_COL.items():
        try:
            wks = sh.worksheet(sheet_name)
            all_vals = wks.get_all_values()
            total = len(all_vals) - 1
            sample_count = 0
            for i in range(1, len(all_vals)):
                cell_val = str(all_vals[i][id_col]).strip() if id_col < len(all_vals[i]) else ""
                if cell_val.startswith(SAMPLE_PREFIX):
                    sample_count += 1
            real_count = total - sample_count
            print(f"  {sheet_name:25s} 전체: {total:3d}행  |  실제: {real_count:3d}  |  샘플: {sample_count:3d}")
        except Exception as e:
            print(f"  {sheet_name:25s} ❌ {e}")

    print("=" * 60)


