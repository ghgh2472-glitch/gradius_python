def reset_all():
    """SAMPLE- 접두사가 붙은 모든 행 삭제"""
    client = db.get_connection()
    if not client:
        print("❌ Google Sheets 연결 실패")
        return False

    sh = client.open_by_key(db.SHEET_ID)
    print("=" * 60)
    print("🗑️  샘플 데이터 삭제 시작 (접두사: 'SAMPLE-')")
    print("=" * 60)

    total_deleted = 0
    for sheet_name, id_col in SHEET_INQ_ID_COL.items():
        print(f"\n🔍 {sheet_name}...")
        try:
            wks = sh.worksheet(sheet_name)
            all_vals = wks.get_all_values()

            # 삭제할 행 인덱스 수집 (뒤에서부터 삭제해야 인덱스 안 밀림)
            rows_to_delete = []
            for i in range(1, len(all_vals)):  # 헤더 제외
                cell_val = str(all_vals[i][id_col]).strip() if id_col < len(all_vals[i]) else ""
                if cell_val.startswith(SAMPLE_PREFIX):
                    rows_to_delete.append(i + 1)  # 1-based row number

            if rows_to_delete:
                # 뒤에서부터 삭제
                for row_num in reversed(rows_to_delete):
                    wks.delete_rows(row_num)
                    time.sleep(0.2)
                print(f"   🗑️  {len(rows_to_delete)}행 삭제")
                total_deleted += len(rows_to_delete)
            else:
                print(f"   ✅ 샘플 데이터 없음")

        except Exception as e:
            print(f"   ❌ 오류: {e}")

    # 배정기록은 배정ID(SA-)로도 체크
    print(f"\n🔍 배정기록 (배정ID 'SA-' 추가 체크)...")
    try:
        wks = sh.worksheet("배정기록")
        all_vals = wks.get_all_values()
        rows_to_delete = []
        for i in range(1, len(all_vals)):
            assign_id = str(all_vals[i][0]).strip() if all_vals[i] else ""
            inq_id = str(all_vals[i][1]).strip() if len(all_vals[i]) > 1 else ""
            if assign_id.startswith("SA-") and not inq_id.startswith(SAMPLE_PREFIX):
                rows_to_delete.append(i + 1)
        if rows_to_delete:
            for row_num in reversed(rows_to_delete):
                wks.delete_rows(row_num)
                time.sleep(0.2)
            print(f"   🗑️  추가 {len(rows_to_delete)}행 삭제")
            total_deleted += len(rows_to_delete)
        else:
            print(f"   ✅ 추가 삭제 없음")
    except Exception as e:
        print(f"   ❌ 오류: {e}")

    print(f"\n" + "=" * 60)
    print(f"🎉 총 {total_deleted}행 삭제 완료!")
    print("=" * 60)

    try:
        db.invalidate_data()
    except:
        pass
    return True


